import { createContext, useContext, type ReactNode } from 'react';

export type LanguagePreference = 'system' | 'zh-CN' | 'en-US';
export type Locale = 'zh-CN' | 'en-US';

export function resolveLocale(preference: LanguagePreference): Locale {
  if (preference !== 'system') return preference;
  const language = typeof navigator === 'undefined' ? 'zh-CN' : navigator.language;
  return language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function currentLocale(): Locale {
  try {
    const saved = localStorage.getItem('oj-insight.preferences');
    if (!saved) return resolveLocale('system');
    const preference = (JSON.parse(saved) as { language?: LanguagePreference }).language;
    return resolveLocale(preference === 'system' || preference === 'en-US' || preference === 'zh-CN' ? preference : 'zh-CN');
  } catch {
    return 'zh-CN';
  }
}

